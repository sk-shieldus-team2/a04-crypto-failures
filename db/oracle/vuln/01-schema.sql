-- 최초 DB 생성 시 1회만 실행 (다시 실행하려면: docker compose down -v 후 up)
-- 대상: XEPDB1 / 카드사 DB (A04 실습용)

ALTER SESSION SET CONTAINER = XEPDB1;
ALTER USER team2 QUOTA UNLIMITED ON USERS;

-- 1) 고객
CREATE TABLE team2.users (
    id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username     VARCHAR2(50)  NOT NULL UNIQUE,   -- 로그인 아이디
    password     VARCHAR2(100) NOT NULL,          -- 평문 저장 (A04)
    name         VARCHAR2(50)  NOT NULL,
    ssn          VARCHAR2(200),                   -- 주민번호
    birth        DATE,
    age          NUMBER,
    phone        VARCHAR2(20),
    address      VARCHAR2(200),
    status       VARCHAR2(20)  DEFAULT '정상',    -- 정상/탈퇴/정지
    income       NUMBER,                          -- 소득정보
    credit_grade VARCHAR2(10),                    -- 신용등급
    job          VARCHAR2(50),
    role         VARCHAR2(20)  DEFAULT 'USER' NOT NULL,  -- USER/ADMIN
    created_at   DATE          DEFAULT SYSDATE
);

-- 2) 카드 (고객 1명이 여러 카드)
CREATE TABLE team2.credit (
    card_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      NUMBER NOT NULL,                 -- FK → users.id
    account_no   VARCHAR2(50),                    -- 계좌번호
    card_no      VARCHAR2(30),                    -- 카드번호
    brand        VARCHAR2(30),                    -- VISA/MASTER 등
    issued_date  DATE,                            -- 발급일
    expiry       VARCHAR2(10),                    -- 유효기간 (MM/YY)
    card_status  VARCHAR2(20)  DEFAULT '정상',    -- 정상/정지/분실
    product_name VARCHAR2(100),                   -- 상품명
    card_type    VARCHAR2(20),                    -- 신용/체크
    cvc          VARCHAR2(10),                    -- CVC
    CONSTRAINT fk_credit_user FOREIGN KEY (user_id) REFERENCES team2.users(id)
);

-- 3) 결제 (카드 1장으로 여러 결제)
CREATE TABLE team2.payment (
    payment_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id           NUMBER NOT NULL,            -- FK → credit.card_id
    merchant_name     VARCHAR2(100),              -- 가맹점명
    merchant_category VARCHAR2(50),               -- 업종
    amount            NUMBER,                     -- 결제금액
    paid_at           DATE          DEFAULT SYSDATE,  -- 결제일시
    installment       NUMBER        DEFAULT 0,    -- 할부 개월 (0=일시불)
    payment_status    VARCHAR2(20)  DEFAULT '승인',  -- 승인/취소
    CONSTRAINT fk_payment_card FOREIGN KEY (card_id) REFERENCES team2.credit(card_id)
);

